"""Fits a high-resolution redraw of one of DOPE's pictures onto the original and writes the aligned picture.

    python3 tools/align_art.py NAME REDRAW.png [REDRAW2.png] [--out art/NAME.png]   (inside the toolbox: numpy + PIL)
    python3 tools/align_art.py --upload NAME OUT.png [--part K]          the nearest-neighbour picture to upload
    python3 tools/align_art.py --sheet OUT.jpg NAME [NAME ...]           comparison sheet of art/NAME.png vs originals

Adapted from stars/remake/tools/align_art.py. NAME is a picture of dope/re/dump/pictures/ (written by the
decompilers' picture dumps: the file's indices with the palette the demo shows them with), see `SPECS`:

- screen pictures (320x200: p2-background, p3-nebula, p4-chequerboard, p5-swirl, p7-horizon) and the 70x44 labels
  are shown at 4:3, one original pixel 1.2 times as tall as wide;
- p7-dope (320x64, pasted on screen rows 50..113) and p2-credits (320x128, four strips of 32 rows) are screen pixels
  too; they are uploaded on a larger black canvas of a shape the generator makes (3:1, 3:2), see `canvas`;
- p2-credits is a coverage mask: the index minus 0x80 (0..62) is the text intensity; it is uploaded and written as
  grey (grey = 255 * x / 63), white text on black;
- p1-logo is a shade map: the indices 0..63 are shade levels coloured through two ramps (notes-core.md, section 8);
  it is uploaded and written as grey (grey = 255 * v / 63) and covers the logo's 1024 x 195 pixels (picture rows
  1..195) at 4:3, on a 3:1 canvas;
- the env maps have square texels: p5-envmaps is two 128x128 maps side by side (gold, red), each uploaded and fitted
  on its own and written side by side again at one scale; p6-envmap is only its drawn left half (blue clouds,
  columns 0..127; the right half is generated by the demo). The gold map's column 127 holds red indices that are
  never read: the upload repeats column 126 there.
The labels and "dope" are grey in the original and are written exactly grey (R = G = B); the credits and the logo
are written as 8-bit greyscale PNGs. The comparison sheet shows the logo coloured through its file palette (B).

The fit maps redraw pixel coordinates (x, y) to original pixel coordinates (u, v):
    u = sx * x + tx,   v = sy * y + ty
A redraw that has the upload's framing and fills its frame has sx = CW / width, sy = CH / height and the offset of
the canvas (CW x CH original pixels, the original at (cx, cy) in it). The fit compares both pictures in the
original's grid (the redraw area-averaged into it, both blurred so that detail the original does not have does not
count): a brute-force search over scale and offset on a coarse grid, then Nelder-Mead on (scale, aspect, tx, ty)
with less and less blur. It prints the scale and offset and the residual (RMS of the RGB difference 0..255 in the
original's grid, plain and with a 1-pixel blur, the share of pixels where one picture is background and the other
is not, and the correlation of the two pictures' detail, see `Fit.residual`), and writes the redraw resampled to
cover exactly the original's frame at the redraw's own pixel size (output width = W / sx, height from the pixel
aspect); where the redraw does not reach, it pads with the original's background colour.

Options:
  --out FILE        output (default ../art/NAME.png next to this script)
  --uniform         keep the redraw's pixels square (one scale), instead of fitting x and y separately
  --range R         search offsets up to R original pixels and scales up to 1 +- R/100 (default 32; labels and
                    env maps 12)
  --part K          --upload: which part of a picture made of several (p5-envmaps: 0 gold, 1 red)
  --match           after the fit, give the redraw the original's colours: per-channel tone curves from quantile
                    matching in the original's grid (see `colour_curves`); for redraws that came out darker or
                    with shifted colours. Monotone, so shapes and detail are kept
"""
import argparse
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
PICTURES = os.path.join(HERE, '..', '..', 're', 'dump', 'pictures')
SCREEN_ASPECT = 1.2  # an original screen pixel is 1.2 times as tall as wide on a 4:3 screen

# kind: 'screen' (RGB through the palette), 'mask' (credits: index - 0x80 as grey), 'shade' (logo: index as grey).
# rows: the picture rows that make the frame. canvas: the upload's display shape (width / height) when it is not
# the frame's own. parts: column ranges fitted (and uploaded) on their own. aspect: pixel height / width.
# grey: the original is grey (labels, "dope"), the output is made exactly grey (R = G = B).
SCREEN = dict(kind='screen', aspect=SCREEN_ASPECT, up=(5, 6))
LABEL = dict(kind='screen', aspect=SCREEN_ASPECT, up=(15, 18), range=12, grey=True)
ENVMAP = dict(kind='screen', aspect=1.0, up=(10, 10), range=12)
SPECS = {
    'p2-background': SCREEN,
    'p3-nebula': SCREEN,
    'p4-chequerboard': SCREEN,
    'p5-swirl': SCREEN,
    'p7-horizon': SCREEN,
    'p7-dope': dict(SCREEN, canvas=3.0, grey=True),
    'p2-credits': dict(SCREEN, kind='mask', canvas=1.5),
    'p1-logo': dict(SCREEN, kind='shade', rows=(1, 196), canvas=3.0),
    'p5-envmaps': dict(ENVMAP, parts=[(0, 128), (128, 256)]),
    'p6-envmap': dict(ENVMAP, parts=[(0, 128)]),
}
for _n in ('p2-label-blur', 'p3-label-phong', 'p4-label-fire-clouds', 'p4-label-fractal-scape', 'p5-label-env',
           'p5-label-bump', 'p6-label-shadow', 'p6-label-morph', 'p6-label-metal', 'p7-label-light',
           'p7-label-world'):
    SPECS[_n] = LABEL


def spec(name):
    if name not in SPECS:
        sys.exit('unknown picture %s (one of %s)' % (name, ', '.join(SPECS)))
    return SPECS[name]


def load_original(name, path=None):
    """The frame as RGB (h, w, 3) float and its background colour. Masks and shade maps come as grey."""
    s = spec(name)
    im = Image.open(path or os.path.join(PICTURES, name + '.png'))
    idx = np.asarray(im).astype(np.int64)
    if s['kind'] == 'mask':
        g = np.clip(idx - 0x80, 0, 63) * 255.0 / 63.0
        rgb = np.repeat(g[..., None], 3, axis=2)
    elif s['kind'] == 'shade':
        rgb = np.repeat((idx * 255.0 / 63.0)[..., None], 3, axis=2)
    else:
        pal = im.getpalette()[:768]
        pal = np.array(pal + [0] * (768 - len(pal)), np.float64).reshape(256, 3)
        rgb = pal[idx]
        if name == 'p5-envmaps':
            rgb[:, 127] = rgb[:, 126]  # never read: red indices in the gold map's last column
    if 'rows' in s:
        rgb = rgb[s['rows'][0]:s['rows'][1]]
    border = np.concatenate([rgb[0], rgb[-1], rgb[:, 0], rgb[:, -1]])
    vals, counts = np.unique(border, axis=0, return_counts=True)
    return rgb, vals[counts.argmax()].copy()


def parts(name, rgb):
    """The pieces fitted on their own: list of (column offset, RGB)."""
    return [(a, rgb[:, a:b]) for a, b in spec(name).get('parts', [(0, rgb.shape[1])])]


def canvas(name, w, h):
    """The upload canvas in original pixels (CW, CH) and the frame's position (cx, cy) in it."""
    s = spec(name)
    if 'canvas' not in s:
        return w, h, 0, 0
    ch = int(round(w / s['canvas'] / s['aspect']))
    if ch >= h:
        return w, ch, 0, (ch - h) // 2
    cw = int(round(h * s['aspect'] * s['canvas']))
    return cw, h, (cw - w) // 2, 0


def gauss_kernel(sigma):
    r = max(1, int(np.ceil(3 * sigma)))
    k = np.exp(-0.5 * (np.arange(-r, r + 1) / sigma) ** 2)
    return k / k.sum()


def blur(img, sigma):
    """Separable Gaussian blur of an (h, w, c) array, edges extended."""
    if sigma <= 0:
        return img
    k = gauss_kernel(sigma)
    r = len(k) // 2
    p = np.pad(img, ((r, r), (0, 0), (0, 0)), mode='edge')
    img = sum(k[i] * p[i:i + img.shape[0]] for i in range(len(k)))
    p = np.pad(img, ((0, 0), (r, r), (0, 0)), mode='edge')
    return sum(k[i] * p[:, i:i + img.shape[1]] for i in range(len(k)))


def box_down(img, f):
    h, w = img.shape[0] // f * f, img.shape[1] // f * f
    return img[:h, :w].reshape(h // f, f, w // f, f, -1).mean(axis=(1, 3))


def bilinear(img, x, y, fill):
    """Samples img (h, w, 3; pixel i covers [i, i+1)) at continuous coordinates x, y; outside gives fill."""
    h, w = img.shape[:2]
    xs, ys = x - 0.5, y - 0.5
    x0, y0 = np.floor(xs).astype(int), np.floor(ys).astype(int)
    fx, fy = (xs - x0)[..., None], (ys - y0)[..., None]
    pad = np.empty((h + 2, w + 2, 3))
    pad[:] = fill
    pad[1:-1, 1:-1] = img
    x0c, y0c = np.clip(x0 + 1, 0, w + 1), np.clip(y0 + 1, 0, h + 1)
    x1c, y1c = np.clip(x0 + 2, 0, w + 1), np.clip(y0 + 2, 0, h + 1)
    out = (pad[y0c, x0c] * (1 - fx) * (1 - fy) + pad[y0c, x1c] * fx * (1 - fy) +
           pad[y1c, x0c] * (1 - fx) * fy + pad[y1c, x1c] * fx * fy)
    outside = (x < 0) | (y < 0) | (x >= w) | (y >= h)
    out[outside] = fill
    return out


class Fit:
    def __init__(self, orig, bg, redraw):
        self.orig, self.bg = orig, bg
        self.H, self.W = orig.shape[:2]
        self.rw, self.rh = redraw.shape[1], redraw.shape[0]
        self.redraw = redraw
        self.cache = {}

    def prepare(self, sx):
        # Pre-reduce the redraw so that about two of its pixels fall on one original pixel.
        f = max(1, int(np.floor(1.0 / sx / 2.0)))
        if getattr(self, 'f', None) != f:
            self.f = f
            self.small = box_down(self.redraw, f)

    def sample(self, sx, sy, tx, ty, u, v):
        x = (u - tx) / sx / self.f
        y = (v - ty) / sy / self.f
        return bilinear(self.small, x[None, :].repeat(len(v), 0), y[:, None].repeat(len(u), 1), self.bg)

    def warp(self, p, ss=2):
        """The redraw in the original's grid for p = (sx, sy, tx, ty), area-averaged over ss x ss samples."""
        u = (np.arange(self.W * ss) + 0.5) / ss
        v = (np.arange(self.H * ss) + 0.5) / ss
        return box_down(self.sample(*p, u, v), ss)

    def orig_blurred(self, sigma):
        if sigma not in self.cache:
            self.cache[sigma] = blur(self.orig, sigma)
        return self.cache[sigma]

    def cost(self, p, sigma):
        d = blur(self.warp(p), sigma) - self.orig_blurred(sigma)
        return float(np.mean(d * d))

    def residual(self, p):
        warped = self.warp(p, ss=4)
        rms = np.sqrt(np.mean((warped - self.orig) ** 2))
        rms1 = np.sqrt(np.mean((blur(warped, 1.0) - blur(self.orig, 1.0)) ** 2))
        fg_o = np.abs(self.orig - self.bg).max(axis=2) > 24
        fg_r = np.abs(warped - self.bg).max(axis=2) > 24
        # Correlation of the detail band (Gaussian 2 minus Gaussian 12 pixels) of the brightness: 1 when every
        # shape is where the original has it, whatever the colours; about 0 for unrelated pictures.
        lo, lw = self.orig.mean(axis=2, keepdims=True), warped.mean(axis=2, keepdims=True)
        do, dw = blur(lo, 2.0) - blur(lo, 12.0), blur(lw, 2.0) - blur(lw, 12.0)
        corr = float(np.corrcoef(do.ravel(), dw.ravel())[0, 1])
        return rms, rms1, float(np.mean(fg_o != fg_r)) * 100, corr


def coarse_search(fit, p0, rng, uniform):
    """Brute force over scale (and aspect) around p0 (scaled about the frame's centre) and offset, blurred."""
    W, H = fit.W, fit.H
    q = 4 if min(W, H) >= 100 else 2  # coarse cell in original pixels
    ob = box_down(blur(fit.orig, 0.75 * q), q)
    best = (np.inf, None)
    scales = 1 + np.arange(-rng, rng + 1, 2.5) / 100.0
    aspects = [1.0] if uniform else 1 + np.arange(-4, 4.1, 2) / 100.0
    m = int(np.ceil(rng / q))
    sx0, sy0, tx0, ty0 = p0
    xc, yc = (W / 2 - tx0) / sx0, (H / 2 - ty0) / sy0  # redraw point on the frame's centre
    fit.prepare(sx0)
    h2 = q // 2
    for s in scales:
        for a in aspects:
            sx, sy = sx0 * s, sy0 * s * a
            tx, ty = W / 2 - sx * xc, H / 2 - sy * yc
            # The redraw on a canvas larger than the frame by m cells on every side, sampled every q/2 pixels.
            u = (np.arange((W + 2 * m * q) // h2) + 0.5) * h2 - m * q
            v = (np.arange((H + 2 * m * q) // h2) + 0.5) * h2 - m * q
            img = box_down(blur(fit.sample(sx, sy, tx, ty, u, v), 0.75 * 2), 2)  # one cell = q pixels
            for dy in range(0, 2 * m + 1):
                for dx in range(0, 2 * m + 1):
                    win = img[dy:dy + H // q, dx:dx + W // q]
                    c = np.mean((win - ob[:win.shape[0], :win.shape[1]]) ** 2)
                    if c < best[0]:
                        # Shifting the window right by dx cells moves the redraw left.
                        best = (c, (sx, sy, tx - (dx - m) * q, ty - (dy - m) * q))
    return best[1]


def nelder_mead(f, x0, steps, iters=300, tol=1e-6):
    n = len(x0)
    pts = [np.array(x0, float)]
    for i in range(n):
        p = np.array(x0, float)
        p[i] += steps[i]
        pts.append(p)
    vals = [f(p) for p in pts]
    for _ in range(iters):
        order = np.argsort(vals)
        pts, vals = [pts[i] for i in order], [vals[i] for i in order]
        if abs(vals[-1] - vals[0]) <= tol * (abs(vals[0]) + 1e-12):
            break
        c = np.mean(pts[:-1], axis=0)
        xr = c + (c - pts[-1])
        fr = f(xr)
        if fr < vals[0]:
            xe = c + 2 * (c - pts[-1])
            fe = f(xe)
            pts[-1], vals[-1] = (xe, fe) if fe < fr else (xr, fr)
        elif fr < vals[-2]:
            pts[-1], vals[-1] = xr, fr
        else:
            xc = c + 0.5 * (pts[-1] - c)
            fc = f(xc)
            if fc < vals[-1]:
                pts[-1], vals[-1] = xc, fc
            else:
                for i in range(1, len(pts)):
                    pts[i] = pts[0] + 0.5 * (pts[i] - pts[0])
                    vals[i] = f(pts[i])
    i = int(np.argmin(vals))
    return pts[i]


def refine(fit, p, uniform):
    sx, sy, tx, ty = p
    fit.prepare(sx)
    for sigma in (3.0, 1.5, 0.75):
        if uniform:
            def f(q):
                return fit.cost((sx * np.exp(q[0]), sy * np.exp(q[0]), tx + q[1], ty + q[2]), sigma)
            q = nelder_mead(f, [0, 0, 0], [0.01, 1.0, 1.0])
            sx, sy, tx, ty = sx * np.exp(q[0]), sy * np.exp(q[0]), tx + q[1], ty + q[2]
        else:
            def f(q):
                return fit.cost((sx * np.exp(q[0]), sy * np.exp(q[0] + q[1]), tx + q[2], ty + q[3]), sigma)
            q = nelder_mead(f, [0, 0, 0, 0], [0.01, 0.005, 1.0, 1.0])
            sx, sy = sx * np.exp(q[0]), sy * np.exp(q[0] + q[1])
            tx, ty = tx + q[2], ty + q[3]
    return sx, sy, tx, ty


def fit_picture(orig, bg, red, p0, rng, uniform):
    fit = Fit(orig, bg, red)
    p = refine(fit, coarse_search(fit, p0, rng, uniform), uniform)
    return p, fit.residual(p), fit.residual(p0)


def colour_curves(orig, red, p, bg):
    """Per-channel tone curves that give the redraw the original's colour distribution: quantile matching of the
    redraw in the original's grid (area-averaged) against the original, both blurred by 1 pixel so that the
    original's dithering and colour steps do not count. Monotone, so every shape and edge stays; returns a function
    of an (h, w, 3) array 0..255."""
    fit = Fit(orig, bg, red)
    fit.prepare(p[0])
    w, o = blur(fit.warp(p, ss=4), 1.0), blur(orig, 1.0)
    q = np.linspace(0, 100, 257)
    curves = []
    for c in range(3):
        xr, xo = np.percentile(w[..., c], q), np.percentile(o[..., c], q)
        xr = np.maximum.accumulate(xr) + np.arange(len(xr)) * 1e-6  # strictly increasing for interp
        # Beyond the redraw's range (its full-resolution pixels reach further than the averaged ones): slope 1.
        curves.append((np.concatenate([[min(0.0, xr[0] - 1)], xr, [max(255.0, xr[-1] + 1)]]),
                       np.concatenate([[xo[0] - xr[0] + min(0.0, xr[0] - 1)], xo,
                                       [xo[-1] + max(255.0, xr[-1] + 1) - xr[-1]]])))

    def apply(a):
        out = np.empty_like(a, dtype=np.float64)
        for c, (xp, fp) in enumerate(curves):
            out[..., c] = np.interp(a[..., c], xp, np.clip(fp, 0, 255))
        return out
    return apply


def render(img, size, p, scale_uv, fill):
    """Resamples img (PIL) so that output pixel (X, Y) shows original coordinates (X * su, Y * sv) under fit p."""
    sx, sy, tx, ty = p
    su, sv = scale_uv
    return img.transform(size, Image.AFFINE, (su / sx, 0, -tx / sx, 0, sv / sy, -ty / sy), resample=Image.BICUBIC,
                         fillcolor=fill)


def report(name, p, res, res0, p0, aspect):
    sx, sy, tx, ty = p
    rel, rely = sx / p0[0], sy / p0[1]
    print('  scale %.4f x %.4f of frame-filling (sx %.5f, sy %.5f original px per redraw px, pixel aspect %.4f), '
          'offset (%.2f, %.2f) original px (frame-filling: %.2f, %.2f)'
          % (rel, rely, sx, sy, sy * aspect / sx, tx, ty, p0[2], p0[3]))
    print('  residual: RMS %.1f, blurred 1 px %.1f, background mismatch %.2f %%, detail correlation %.3f   '
          '(redraw just stretched to the frame: %.1f, %.1f, %.2f %%, %.3f)' % (res + res0))
    print('  | %s | %.4f x %.4f | %+.1f, %+.1f | %.1f / %.1f / %.1f %% / %.2f |'
          % ((name, rel, rely, tx - p0[2], ty - p0[3]) + res))


def align(a):
    name = a.name
    s = spec(name)
    rgb, bg = load_original(name)
    pieces = parts(name, rgb)
    if len(a.redraws) != len(pieces):
        sys.exit('%s needs %d redraws (one per part)' % (name, len(pieces)))
    aspect = s['aspect']
    fits = []
    for k, ((col, orig), path) in enumerate(zip(pieces, a.redraws)):
        img = Image.open(path).convert('RGB')
        red = np.asarray(img, np.float64)
        rw, rh = red.shape[1], red.shape[0]
        H, W = orig.shape[:2]
        CW, CH, cx, cy = canvas(name, W, H)
        p0 = (CW / rw, CH / rh, -cx, -cy)
        p, res, res0 = fit_picture(orig, bg, red, p0, a.range or s.get('range', 32), a.uniform)
        print('%s%s: redraw %dx%d of a %dx%d canvas (frame at %d, %d)'
              % (name, ' part %d' % k if len(pieces) > 1 else '', rw, rh, CW, CH, cx, cy))
        report(name + ('.%d' % k if len(pieces) > 1 else ''), p, res, res0, p0, aspect)
        if a.match:
            red = np.clip(colour_curves(orig, red, p, bg)(red), 0, 255)
            fm = Fit(orig, bg, red)
            fm.prepare(p[0])
            print('  after the colour match: | %.1f / %.1f / %.1f %% / %.2f |' % fm.residual(p))
            img = Image.fromarray(np.round(red).astype(np.uint8))
        fits.append((img, orig, p))
    # Output: the frame at the redraws' own horizontal pixel size (one scale for all parts).
    k_out = float(np.median([1.0 / p[0] for _, _, p in fits]))  # output pixels per original pixel, horizontally
    H = rgb.shape[0]
    outs = []
    for img, orig, p in fits:
        W = orig.shape[1]
        ow, oh = int(round(W * k_out)), int(round(H * aspect * k_out))
        outs.append(render(img, (ow, oh), p, (W / ow, H / oh), tuple(int(round(c)) for c in bg)))
    out = Image.new('RGB', (sum(o.size[0] for o in outs), outs[0].size[1]))
    x = 0
    for o in outs:
        out.paste(o, (x, 0))
        x += o.size[0]
    if s['kind'] in ('mask', 'shade'):
        out = out.convert('L')  # grey: 255 * coverage or 255 * shade / 63
    elif s.get('grey'):
        out = out.convert('L').convert('RGB')
    out_path = a.out or os.path.join(HERE, '..', 'art', name + '.png')
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    out.save(out_path, optimize=True)
    print('  -> %s %dx%d %s (%.0f kB)' % (os.path.basename(out_path), out.size[0], out.size[1], out.mode,
                                         os.path.getsize(out_path) / 1000))


def upload(a):
    """The picture to give the image generator: nearest-neighbour (see SPECS 'up'), on its canvas."""
    name = a.name
    s = spec(name)
    rgb, bg = load_original(name)
    col, orig = parts(name, rgb)[a.part]
    H, W = orig.shape[:2]
    CW, CH, cx, cy = canvas(name, W, H)
    c = np.empty((CH, CW, 3))
    c[:] = bg
    c[cy:cy + H, cx:cx + W] = orig
    fx, fy = s['up']
    img = Image.fromarray(np.round(c).astype(np.uint8))
    if s['kind'] in ('mask', 'shade'):
        img = img.convert('L')
    img.resize((CW * fx, CH * fy), Image.NEAREST).save(a.redraws[0])
    print('%s: %dx%d' % (a.redraws[0], CW * fx, CH * fy))


def display(name, rgb, colour):
    """An original or a redraw as shown (RGB uint8): the logo through palette B (its file palette)."""
    if name == 'p1-logo' and colour:
        pal = np.array(Image.open(os.path.join(PICTURES, 'p1-logo.png')).getpalette()[:192], np.float64)
        pal = pal.reshape(64, 3)
        sh = rgb[..., 0] * 63.0 / 255.0
        i0 = np.clip(np.floor(sh).astype(int), 0, 62)
        f = (sh - i0)[..., None]
        rgb = pal[i0] * (1 - f) + pal[i0 + 1] * f
    return Image.fromarray(np.clip(np.round(rgb), 0, 255).astype(np.uint8))


def sheet(a):
    try:
        font = ImageFont.truetype('DejaVuSans-Bold.ttf', 16)
    except OSError:
        font = ImageFont.load_default()
    rows, pending = [], []

    def panel(name, pw):
        rgb, _ = load_original(name)
        rgb = np.concatenate([o for _, o in parts(name, rgb)], axis=1)  # p6-envmap: the drawn left half
        H, W = rgb.shape[:2]
        ph = int(round(pw * H * spec(name)['aspect'] / W))
        left = display(name, rgb, True).resize((pw, ph), Image.NEAREST)
        art = os.path.join(a.art, name + '.png')
        pair = Image.new('RGB', (2 * pw, ph))
        pair.paste(left, (0, 0))
        if os.path.exists(art):
            r = np.asarray(Image.open(art).convert('RGB'), np.float64)
            right = display(name, r, True).resize((pw, ph), Image.LANCZOS)
            label = '%s: original | redraw' % name
        else:
            right = left
            label = '%s: original | kept' % name
        pair.paste(right, (pw, 0))
        d = ImageDraw.Draw(pair)
        d.line([(pw, 0), (pw, ph)], fill=(80, 80, 80), width=2)
        d.text((6, 4), label, fill=(255, 255, 0), font=font, stroke_width=2, stroke_fill=(0, 0, 0))
        return pair

    for name in a.nums:
        small = '-label-' in name
        pair = panel(name, 400 if small else 800)
        if small:
            pending.append(pair)
            if len(pending) == 2:
                row = Image.new('RGB', (1600, max(p.size[1] for p in pending)))
                row.paste(pending[0], (0, 0))
                row.paste(pending[1], (800, 0))
                rows.append(row)
                pending = []
        else:
            rows.append(pair)
    if pending:
        row = Image.new('RGB', (1600, pending[0].size[1]))
        row.paste(pending[0], (0, 0))
        rows.append(row)
    out = Image.new('RGB', (1600, sum(r.size[1] + 4 for r in rows)), (40, 40, 40))
    y = 0
    for r in rows:
        out.paste(r, (0, y))
        y += r.size[1] + 4
    out.save(a.sheet, quality=88)
    print('%s: %d rows, %dx%d' % (a.sheet, len(rows), out.size[0], out.size[1]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('name', nargs='?')
    ap.add_argument('redraws', nargs='*')
    ap.add_argument('--out')
    ap.add_argument('--art', default=os.path.join(HERE, '..', 'art'))
    ap.add_argument('--uniform', action='store_true')
    ap.add_argument('--range', type=float, default=0)
    ap.add_argument('--part', type=int, default=0)
    ap.add_argument('--match', action='store_true')
    ap.add_argument('--sheet')
    ap.add_argument('--upload', action='store_true')
    a = ap.parse_args()
    if a.sheet:
        a.nums = [x for x in [a.name] + a.redraws if x]
        sheet(a)
    elif a.upload and a.name and len(a.redraws) == 1:
        upload(a)
    elif a.name and a.redraws:
        align(a)
    else:
        ap.print_help()
        sys.exit(1)


if __name__ == '__main__':
    main()
