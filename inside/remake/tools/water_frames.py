"""Writes src/scenes/water_frames.h: the capture's frame schedule in the water part (inside/re/notes-water.md 6.1, 9).

    python3 tools/water_frames.py > src/scenes/water_frames.h        (inside the toolbox: numpy)

Reads inside/re/full.flips (the records that show the part's frames) and inside/re/models/water/run2.pkl (that
folder's run_inside.py --water-dump over the whole part, see its README: per frame the M the fish read, the fish
states and the rand seeds; its frames equal full.frames). Finds the fish updates that read a later M (a timer
interrupt during the frame's 8 updates) by replaying every fish update with models/water/water_model.py against the
next frame's state, and checks that the rand() sequence from the seed at the first frame gives every frame's seed.
These are values measured from the capture, not data of the original program.
"""
import collections
import os
import pickle
import sys

import numpy as np

RE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 're')
os.chdir(os.path.join(RE, 'models', 'water'))   # water_model.py finds INSIDE.DAT relative to it
sys.path.insert(0, os.getcwd())
import water_model as WM  # noqa: E402

FRAME_FN = '407d78'
flips, after = [], None
for line in open(os.path.join(RE, 'full.flips')):
    if line.startswith('#'):
        continue
    f = line.split()
    if f[7] == FRAME_FN:
        flips.append(int(f[1]))
    elif flips and after is None:
        after = int(f[1])
D = pickle.load(open('run2.pkl', 'rb'))
F = D['frames']
# The copy at the part's first record shows the screen the start cleared; frame 1 (drawn with M = 33719 right after the
# start) is shown at the second; the last frame at the next part's first record (full.flips lists it under that part).
assert len(flips) == len(F) + 1, (len(flips), len(F))
shown = flips[1:] + [after]
for k, f in enumerate(F):   # a frame flipped after the retrace callback of its record is copied at the next one
    assert shown[k + 1] - f['flip_refresh'] in (0, 1), (k, f['flip_refresh'], shown[k + 1])
first = flips[0]
c = [33719] + [f['c'] for f in F]          # frame 0: notes-water.md 3 (fish_init.py)
SEED0 = 0xc249a56a                         # seed_start.py

# per fish: the M its update read (c, c + 1 or c + 2), from the next frame's state
late = []
seed = SEED0
for k in range(len(F) - 1):
    f, g = F[k], F[k + 1]
    assert f['seed'] == seed or k == 0, k
    rnd = WM.Rand(f['seed'])
    for i in range(8):
        found = None
        for dc in range(3):
            x = {'pos': list(f['fish'][i]['pos']), 'mat': list(f['fish'][i]['mat']),
                 'verts': [list(v) for v in f['fish'][i]['verts']]}
            r2 = WM.Rand(rnd.seed)
            log = {'a': [], 's': [], 'proj': []}
            WM.fish_update(i, x, f['c'] + dc, r2, np.zeros(64000, np.int16), log)
            if x['pos'] == list(g['fish'][i]['pos']) and x['mat'] == list(g['fish'][i]['mat']):
                found = dc
                break
        assert found is not None, (k, i)
        if found:
            late.append((k + 1, i, found))
        rnd = r2
    WM.drops(rnd, np.zeros(64000, np.int16))
    assert rnd.seed == g['seed'], k
    seed = g['seed']

dm = [c[j] - 4 * shown[j] for j in range(len(shown))]
steps = [shown[0] - first] + [shown[j] - shown[j - 1] for j in range(1, len(shown))]
print('// Generated by tools/water_frames.py from inside/re/full.flips and inside/re/models/water/run2.pkl: the water')
print('// part\'s frame schedule in the capture (inside/re/notes-water.md 6.1, 9). Values measured from the capture:')
print('// stepping the fish, the drops and the ripple with these clocks from kSeed reproduces the capture\'s frames.')
print('#pragma once')
print('#include <cstdint>')
print()
print('namespace water_frames {')
print('// Frame j is shown from record kFirstRecord + shown_j: kShowSteps[j] = shown_j - shown_(j-1), shown_(-1) = 0; the')
print('// part\'s first record in the capture (its routines are set) shows the screen its start cleared.')
print('inline constexpr int kFirstRecord = %d;' % first)
print('inline constexpr int kFrames = %d;' % len(shown))
print('inline constexpr uint8_t kShowSteps[kFrames] = {')
for i in range(0, len(steps), 32):
    print('    ' + ' '.join('%d,' % s for s in steps[i:i + 32]))
print('};')
print('// M = [0x4248c4] that frame j\'s fish read: 4 (kFirstRecord + shown_j) + kClock[j].')
print('inline constexpr int16_t kClock[kFrames] = {')
for i in range(0, len(dm), 18):
    print('    ' + ' '.join('%d,' % s for s in dm[i:i + 18]))
print('};')
# a timer interrupt during a frame: every later fish of the frame reads M + 1
firsts = {}
for frame, fish, d in late:
    assert d == 1
    firsts[frame] = min(firsts.get(frame, 8), fish)
for frame, fish in firsts.items():
    assert sorted(i for f, i, _ in late if f == frame) == list(range(fish, 8)), frame
print('// Frames in which a timer interrupt came during the fish updates: fish `fish` and the ones after it read M + 1.')
print('struct Late { int16_t frame; int16_t fish; };')
print('inline constexpr Late kLate[] = {')
items = sorted(firsts.items())
for i in range(0, len(items), 8):
    print('    ' + ' '.join('{%d, %d},' % t for t in items[i:i + 8]))
print('};')
retrace = set(c - 4 * refresh for refresh, _, c, _ in D['ticks'])
assert len(retrace) == 1, retrace
print('// M of the retrace callback of record k (the tick routine\'s calls): 4 k + kRetrace (notes-core.md 1.2).')
print('inline constexpr int kRetrace = %d;' % retrace.pop())
print('// Watcom rand()\'s seed before the part\'s first frame.')
print('inline constexpr uint32_t kSeed = %#x;' % SEED0)
print('}  // namespace water_frames')
sys.stderr.write('frames %d, M offsets %s, late fish updates %d\n' % (
    len(shown), sorted(collections.Counter(dm).items()), len(late)))
