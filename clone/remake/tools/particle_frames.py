"""Writes src/scenes/particle_frames.h: the frame times of the capture in the particle parts (1, 6, 3, 1 again).

    python3 tools/particle_frames.py [../re/full.flips] > src/scenes/particle_frames.h

The look of parts 1, 3 and 6 depends on the frame steps (clone/re/notes-particles.md section 7): the remake steps
them at the capture's frames, so that the particles, the spawn order and the random numbers are the capture's. One
list per run of a part: the timer (PIT clocks, xmpGetTimer) of the frame before the part's first frame (the origin),
the timer of the first frame, and the differences between consecutive frames. These are values measured from the
capture (clone/re/full.flips column 4), not data of the original program.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 're', 'full.flips')
NONE = -(1 << 39)

rows = []
for line in open(path):
    if line.startswith('#'):
        continue
    f = line.split()
    rows.append((int(f[0]), int(f[3]), int(f[5])))   # flip, timer, part

runs = []
for i, (flip, timer, part) in enumerate(rows):
    if part not in (1, 3, 6):
        continue
    if not runs or runs[-1]['part'] != part or rows[i - 1][2] != part:
        runs.append({'part': part, 'idx': []})
    runs[-1]['idx'].append(i)

names = {0: 'kSwarmFirst', 1: 'kRing', 2: 'kDots', 3: 'kSwarmAgain'}
out = []
out.append('// Generated by tools/particle_frames.py from clone/re/full.flips: the timer values (PIT clocks since the music')
out.append('// start, xmpGetTimer) the capture drew its frames with in the particle parts. Values measured from the capture.')
out.append('// Per run: the timer of the frame before the first one (the origin, the previous part\'s last frame), the timer of')
out.append('// the first frame, then the steps from frame to frame. Part 1\'s first run: its first frame (flip 2) is drawn before')
out.append('// any timer read, with the image\'s dt (6.0); the list starts with the second (flip 3), whose dt main computes')
out.append('// from t70_prev = 0, so its origin is timer 0.')
out.append('#pragma once')
out.append('#include <cstdint>')
out.append('')
out.append('namespace particles {')
for n, run in enumerate(runs):
    idx = run['idx']
    if run['part'] == 1 and rows[idx[0]][1] < NONE:
        idx = idx[1:]                     # flip 2: no timer yet (dt = the image's 6.0)
        origin = 0
    else:
        origin = rows[idx[0] - 1][1]
    timers = [rows[i][1] for i in idx]
    steps = [b - a for a, b in zip(timers, timers[1:])]
    assert all(0 < s < 65536 for s in steps)
    name = names[n]
    out.append('// part %d, flips %d..%d' % (run['part'], rows[idx[0]][0], rows[idx[-1]][0]))
    out.append('inline constexpr int64_t %sOrigin = %d, %sFirst = %d;' % (name, origin, name, timers[0]))
    out.append('inline constexpr uint16_t %sSteps[%d] = {' % (name, len(steps)))
    for k in range(0, len(steps), 16):
        out.append('    ' + ', '.join(str(s) for s in steps[k:k + 16]) + ',')
    out.append('};')
out.append('}  // namespace particles')
print('\n'.join(out))
